// 场景装配：地图 -> 一份**绘制列表**（格坐标 + 精灵标识符 + 朝向 + 深度键）。
//
// **本文件不含任何像素，也不依赖 raylib。** 这是刻意的，理由有两条：
//
//   1. `地图与场景设计.md` 第 7 节要求像素几何只有一个来源（`_sprite_meta.json`），
//      所以「一格多少像素」只能是渲染层的知识。本层只回答「哪一格画哪张图、
//      按什么顺序画」。
//   2. **`render/` 默认不参与构建**（CMakeLists.txt 的 RTS_BUILD_RENDER=OFF），
//      挂在它下面的测试在默认构建里根本不存在、ctest 照样全绿。而 4.2.1 那四条规则
//      恰恰是「只值一行代码但错了才发现」的那种。把它们放在这个**始终构建**的库里，
//      它们就一定被测到。
//
// 规范来源是 `tools/sprite_gen/preview_map.py` 的「契约」段（4.2.1 明文声明），
// 本文件是它的 C++ 移植。两者不一致时以那份 Python 为准并回来修这里。

#ifndef GAME_SCENE_MODEL_HPP
#define GAME_SCENE_MODEL_HPP

#include <cstdint>
#include <string_view>
#include <vector>

#include "game/map_data.hpp"
#include "rts/types.hpp"

namespace game {

// 四个朝向，取值与精灵文件名里的后缀一致（`<标识符>_<状态>_<朝向>.png`）。
enum class Facing : std::uint8_t { SE, SW, NE, NW };

std::string_view to_string(Facing f) noexcept;

// 绘制列表里的一项。
//
// `sprite` 是**精灵标识符**（"Plain" / "Forest" / "Wall" …），不是文件名——
// 拼文件名要知道状态与帧号，那是渲染层的事。
struct DrawItem {
    rts::GridPos pos{};
    std::string_view sprite;
    Facing facing = Facing::SE;

    // ——实体扩展（机制第一批之后，`BattleScene` 用；静态场景保持默认值）——
    std::string_view state = "idle";   // 精灵状态。渲染侧对没有该状态的实体回落 idle
    int anim = 0;          // 动画相位。渲染侧对帧数取模——帧数是素材侧知识（§7）
    bool continuous = false;           // true ⇒ 用 world 定位（单位在格间移动）
    rts::Vec2 world{};                 // 连续世界坐标（格单位）
    float hp_frac = -1.0f;             // >= 0 ⇒ 渲染侧画血条
    // 屏幕竖直提升，单位是**竖直格边长的倍数**（像素换算归渲染侧，§7 的分界；
    // 换算用 `IsoProjection::tile_z()`，**不是 `tile_h()`**，理由见那里）。
    // 现在只有弹丸用它表达飞行高度。
    float lift = 0.0f;
    // 脚下踩着的那座建筑的**精灵标识符**（空 = 站在地面上）。驻守登顶的单位填它，
    // 渲染侧据该精灵的几何算出抬多少像素，画成「站在墙头」。
    //
    // **为什么不在这里直接给抬升量。** 抬多少是**素材几何**（城墙与门楼的精灵一高
    // 一矮，实测顶端差 25 px），而 §7 把像素几何的唯一来源定为 `_sprite_meta.json`
    // ——`game/` 一旦自己填一个数，那个数就是第二份真相，换素材时它不会跟着变，
    // 且「墙对了门楼错」这种半对的形态最难被发现。所以这里只说**站在什么上面**。
    std::string_view stand_on{};
    // 飞行目的地（世界坐标，格单位）。**只对弹丸精灵有意义**：弹丸是单张
    // FREE 图，方向由渲染侧按「投影后的 aim − world」算屏幕角 2D 旋转
    // （§8.3——等距下世界角 ≠ 屏幕角，所以这里给的是点、不是角）。
    rts::Vec2 aim{};

    // 画家算法的深度键：gi + gj。**叠加物与实体必须在同一个序列里排**，
    // 否则站在岩壁前面的单位不会遮住岩壁。
    int depth() const noexcept { return pos.i + pos.j; }

    // 连续深度键，静态项按**格心**折算（i+j+1 = 格心的 x+y），
    // 于是单位与建筑/景物可以混在同一个序列里排，量纲一致。
    float depth_f() const noexcept {
        return continuous ? world.x + world.y
                          : static_cast<float>(pos.i + pos.j) + 1.0f;
    }
};

// 一格展开成的两张图。**一格要画两张，不是一张**（4.2.1）。
struct TerrainSprites {
    std::string_view tile;      // 底衬地砖，永远非空
    std::string_view overlay;   // 叠加物件，空表示没有
};

// 两遍绘制的两份列表。分开给出，是因为它们的性质不同：
// 地砖是平的、永远不遮挡任何东西，可以先整片铺完；叠加物与实体必须排序。
struct DrawLists {
    std::vector<DrawItem> tiles;    // 第一遍，顺序无所谓
    std::vector<DrawItem> sorted;   // 第二遍，已按深度排好，从前往后画
};

// 把地图装配成绘制列表。无状态，因此做成一组静态函数而不是一个对象——
// 它没有任何需要跨调用保持的东西。
class SceneModel {
public:
    // 地形枚举 -> (底衬地砖, 叠加物)。
    //
    // 只有 Plain* 与 Water 自己就是地砖（元数据里 kind == "tile"：画布正好占满菱形、
    // 锚点在格心、不描边不投影）。Rock / Forest / Bridge 是立体物件——锚点在脚底、
    // 带描边与投影、画布远大于一格，单独贴上去底下是透明的。
    //
    // **桥的底衬是 Water 而不是 Plain**：铺平地会让河在桥这一格视觉上断掉，
    // 读作「水断了一格换成桥」而不是「桥架在水上」。
    static TerrainSprites expand(Terrain t) noexcept;

    // `Plain` 的贴图变体按坐标挑。变体**不占枚举位**（4.1），所以地图文件里没有它，
    // 只能由渲染侧决定；而它必须是**确定**的，否则同一格每帧换一张会闪。
    static std::string_view plain_variant(rts::GridPos p) noexcept;

    // 哪些东西是「线性结构」——它们的朝向由**走向**决定。
    // 岩壁与密林是团块，朝向无所谓，因此不在此列。
    enum class RunKind {
        Wall,    // 墙与门，走向看相邻的墙段
        Bridge,  // 桥，走向看**相邻的水格**（过河的方向），见下
    };

    // 线性结构的朝向由它的**走向**决定，不是固定 SE。
    //
    // 这条极易漏：单位的朝向是「它面朝哪」，而墙的朝向是「它沿哪个方向铺」。
    // 同一段墙沿 gi 铺和沿 gj 铺要用不同的精灵，否则相邻墙段接不上，
    // 一条边在画面上读作一排分开的板子。
    //
    // 哪个朝向对是**实测出来的**（4.2.1.1，`tools/sprite_gen/README.md`
    // 「线性结构的朝向是走向」那节也写着「换素材后要重测」）。这一版重测过，
    // 判据比上一版多一条，结论因此变了——**而且两种线性结构的表是反的**：
    //
    // | 走向 | 墙 / 门 | 桥 | 上一版（两者共用） |
    // |---|---|---|---|
    // | 沿 `gi` | **`NE`** | **`SE`** | `SW` |
    // | 沿 `gj` | **`SE`** | `SW` | `NW` |
    //
    // 反过来不是笔误：`wall-narrow.glb` 与 `bridge-draw.glb` 的长轴本来就不是
    // 同一个轴，而那节自己写着「这取决于模型自身的长轴朝向」。**所以这张表
    // 只能逐模型实测，不能全局共用一份**——上一版共用一份正是它错的根源之一。
    //
    // **多出来的那条判据是「贴得正不正」，不只是「接不接得上」。**
    // 墙板是 180° 对称的（拼起来都无缝），所以每条轴上的两个朝向在「接得上」
    // 这一条判据下**等价**——上一版只测了无缝，于是沿 `gj` 选了 `NW`。
    // 但四个朝向**共用同一个 `ground_anchor`**（`_sprite_meta.json` 逐 ident
    // 一个，不分朝向），而各朝向的内容偏离它的量不同。逐张实测（px，
    // `px_per_tile = 256`；「裁切」= 压在画布右边缘的不透明像素数，>0 即内容被切）：
    //
    // | 精灵 | `SE` | `NE` | `SW` | `NW` |
    // |---|---|---|---|---|
    // | `Wall` 内容中心 − 锚点 x | 0.0 | 0.0 | **+34.5** | **+34.5** |
    // | `Wall` 裁切 | 0 | 0 | **228** | **221** |
    // | `Gate` 内容中心 − 锚点 x | +5.5 | +5.5 | **−32.5** | **−32.5** |
    //
    // 所以**干净的一组是 `{SE, NE}`、脏的是 `{SW, NW}`**；而两条轴各有一个
    // 干净的（`gi` 取 `NE`、`gj` 取 `SE`），本表就是这么来的。
    //
    // > **本段上一版把脏的那组写成了 `NE`/`NW`，那句话是错的**，代价是它让
    // > 上一轮只修了一半：沿 `gj` 从 `NW` 换到 `SE`（对了），沿 `gi` 却留在
    // > `SW`（同样是脏的那组）。于是**东西门看着是对的、南北门仍然错开**
    // > ——池图 12 张里恰好一半一半，读起来像「时好时坏」。2026-09-01 实测订正。
    //
    // 所以这不是给素材缺陷打补丁：同轴两个朝向本来等价，重测只是在等价的两个里
    // 挑了正的那个。素材那一侧的偏移与裁切是另一件事，要靠重渲修（已挂给
    // 精灵流水线那侧），修好之后本表不必再动。
    //
    // **已知残留**：`Wall` 的 `NE` 与 `SE` 在**竖直**方向上不同（内容底边相对锚点
    // 85.3 vs 53.3、顶边 −205.7 vs −258.7），所以横墙与竖墙的板可能差约 32 px
    // （0.2 个竖直格）。那来自模型自身前后不对称（180° 孪生的剪影本该相同、
    // 实测不同），不是选错了朝向；真要抹平得给元数据加**逐朝向锚点**。
    //
    // **桥另有一条**：它的走向是「过河的方向」，即**河的垂直方向**，
    // 而不是「相邻桥格的方向」。一格宽的河上并排两格桥时，后者会让桥板
    // 顺着水流铺——读作「河里漂着两块板」。实现见 .cpp。
    static Facing run_direction(const MapData& map, rts::GridPos p,
                                RunKind kind) noexcept;

    // 墙格是否在**拐角**：gi 方向（左右）与 gj 方向（上下）都连着墙/门。
    //
    // 城圈是切比雪夫方环，四个角格各连着一条横边与一条竖边。`run_direction`
    // 对「左右有墙」的格恒判横板（SW），于是拐角格只画了横的那一边、竖边
    // 缺一格——四个角在画面上是开的（机制上走不进来，纯视觉缺陷，见
    // `rts_core` 的穿角禁令）。调用方据这个函数给拐角格**补画**第二块板。
    static bool is_wall_corner(const MapData& map, rts::GridPos p) noexcept;

    // 资源点 → 地表标记的精灵标识符（`StonePt`/`WoodPt`/`GoldPt`）。
    //
    // 这些标识符**不在精灵流水线里**——资源点不是实体（不进花名册、不进回放），
    // `tools/sprite_gen/` 不为它出图；贴图是一份单独存放的真实素材
    // （`tools/sprite_gen/decals/`，经 `render::SpriteAtlas::register_decal_image`
    // 注册，要 GL 上下文、在 preload 之前调）。
    // 这里只决定「摆上地图时用哪个名字」。标记存在的理由：**资源点必须在
    // 画面上可见**，否则「地图上有金矿」与「玩家眼里没有金矿」同时成立
    // （2026-09-01 试玩反馈：「城内外完全不会刷新金矿」——数据里一直在，
    // 是渲染层从来不画）。
    static std::string_view resource_marker(rts::Resource kind) noexcept;

    // 装配。地砖一遍、叠加物与墙段混排一遍。
    static DrawLists build(const MapData& map);
};

}  // namespace game

#endif  // GAME_SCENE_MODEL_HPP
